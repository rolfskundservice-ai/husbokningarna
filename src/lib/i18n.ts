export function t(lang: string, key: keyof typeof translations.sv): string {
  const l = (lang as Lang) in translations ? (lang as Lang) : "sv";
  const val = (translations[l] as typeof translations.sv)[key];
  return Array.isArray(val) ? val.join(",") : String(val);
}

export function tArr(lang: string, key: keyof typeof translations.sv): string[] {
  const l = (lang as Lang) in translations ? (lang as Lang) : "sv";
  const val = (translations[l] as typeof translations.sv)[key];
  return Array.isArray(val) ? val : [String(val)];
}

export function getTranslations(lang: string) {
  const l = (lang as Lang) in translations ? (lang as Lang) : "sv";
  return translations[l] as typeof translations.sv;
}
